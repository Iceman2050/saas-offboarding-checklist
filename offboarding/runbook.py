"""Generate an ordered markdown revocation runbook."""

from datetime import date

from .tools import PHASE_TITLES, PHASES


def build_runbook(employee_name, employee_email, tools, generated=None):
    """Build the markdown runbook.

    employee_name/email: who is leaving.
    tools: list of tool dicts (catalog or custom) in the order chosen.
    generated: date string; defaults to today (pass a fixed value for
        deterministic output, e.g. in tests or docs).
    """
    generated = generated or date.today().isoformat()
    total_steps = sum(len(t["steps"]) for t in tools)

    lines = []
    lines.append(f"# Offboarding runbook - {employee_name}")
    lines.append("")
    lines.append(f"Generated {generated} - {len(tools)} tools, {total_steps} steps. "
                "Work the phases in order: OAuth/SSO first, then API keys, "
                "then shared credentials, then data.")
    if employee_email:
        lines.append(f"Employee: {employee_email}")
    lines.append("")

    for phase in PHASES:
        lines.append(f"## {PHASE_TITLES[phase]}")
        lines.append("")
        for tool in tools:
            phase_steps = [s for (p, s) in tool["steps"] if p == phase]
            if not phase_steps:
                continue
            lines.append(f"### {tool['name']}")
            if tool.get("doc_url"):
                lines.append(f"Vendor how-to: [{tool.get('doc_title', tool['name'])}]({tool['doc_url']})")
            for step in phase_steps:
                lines.append(f"- [ ] {step}")
            lines.append("")

    lines.append("---")
    lines.append("_Generated by saas-offboarding-checklist. Verify each step in the "
                 "vendor's current docs - admin consoles change._")
    return "\n".join(lines).rstrip() + "\n"


def parse_custom(spec):
    """Parse a --custom spec of the form 'Name|phase|Step text'.

    Returns a tool dict with no vendor doc link.
    """
    parts = [p.strip() for p in spec.split("|", 2)]
    if len(parts) != 3 or not all(parts):
        raise ValueError(
            f"Bad --custom spec {spec!r}; expected 'Name|phase|Step text' "
            f"with phase in {', '.join(PHASES)}"
        )
    name, phase, step = parts
    if phase not in PHASES:
        raise ValueError(
            f"Bad phase {phase!r} in --custom spec; expected one of {', '.join(PHASES)}"
        )
    return {
        "slug": "custom-" + "".join(c if c.isalnum() else "-" for c in name.lower()).strip("-"),
        "name": name,
        "doc_url": "",
        "doc_title": "",
        "steps": [(phase, step)],
    }
